const LanguageContext = createContext();

export function LanguageProvider({ children }) {
  const [currentLanguage, setCurrentLanguage] = useState(() => {
    return localStorage.getItem('nexus_parent_lang') || 'en';
  });

  const changeLanguage = (code) => {
    setCurrentLanguage(code);
    localStorage.setItem('nexus_parent_lang', code);
  };

  const t = (key) => {
    // STRICT RULE: Only the PARENT role can see non-English translations!
    // All other roles (SuperAdmin, DeptAdmin, Teacher, Student, ExamStaff) must be in English.
    try {
      const savedUser = sessionStorage.getItem('nexus_user');
      if (savedUser) {
        const userObj = JSON.parse(savedUser);
        if (userObj?.role && userObj.role !== 'PARENT') {
          return TRANSLATIONS.en[key] || key;
        }
      }
    } catch (e) {}

    const langDict = TRANSLATIONS[currentLanguage] || TRANSLATIONS.en;
    return langDict[key] || TRANSLATIONS.en[key] || key;
  };

  return (
    <LanguageContext.Provider value={{ currentLanguage, changeLanguage, t, languages: LANGUAGES }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    return {
      currentLanguage: 'en',
      changeLanguage: () => {},
      t: (k) => k,
      languages: LANGUAGES
    };
  }
  return context;
}
